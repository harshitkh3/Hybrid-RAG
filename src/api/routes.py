@router.post(
    "/ingest",
    response_model=IngestResponse,
    summary="Trigger document ingestion and indexing",
    description="Loads PDFs from the document directory, splits into chunks, updates BM25 sparse weights, and ingests into Pinecone.",
)
def ingest_endpoint(request: IngestRequest) -> IngestResponse:
    try:
        result = run_ingestion_pipeline(
            docs_dir=request.docs_dir,
            reindex=request.reindex,
        )
        return IngestResponse(**result)
    except Exception as e:
        logger.error("Ingestion failed: %s", e, exc_info=True)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Document ingestion failed: {str(e)}",
        )


@router.get(
    "/health",
    response_model=HealthResponse,
    summary="Service health and index statistics",
    description="Returns current status of the service and Pinecone hybrid index statistics.",
)
def health_endpoint() -> HealthResponse:
    try:
        index = get_or_create_index()
        stats = index.describe_index_stats()
        ns_info = stats.get("namespaces", {}).get(settings.PINECONE_NAMESPACE, {})

        return HealthResponse(
            status="healthy",
            index_name=settings.PINECONE_INDEX_NAME,
            metric=stats.get("metric", "dotproduct"),
            dimension=stats.get("dimension", settings.EMBEDDING_DIMENSION),
            namespace=settings.PINECONE_NAMESPACE,
            namespace_vectors=ns_info.get("vector_count", 0),
            total_index_vectors=stats.get("total_vector_count", 0),
        )
    except Exception as e:
        logger.error("Health check failed: %s", e, exc_info=True)
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail=f"Health check failed: {str(e)}",
        )
