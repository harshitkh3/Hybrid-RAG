import logging
from typing import Optional, Union, Dict, Any
from fastapi import APIRouter, HTTPException, Query, status
from fastapi.responses import StreamingResponse
from src.config import settings
from src.core.pinecone_client import get_or_create_index
from src.generation.rag_chain import ask_question, stream_answer
from src.ingestion.indexer import run_ingestion_pipeline
from src.api.schemas import (
    QueryRequest,
    QueryResponse,
    IngestRequest,
    IngestResponse,
    HealthResponse,
)

logger = logging.getLogger(__name__)

router = APIRouter(prefix="", tags=["RAG"])


@router.post(
    "/ask",
    response_model=QueryResponse,
    summary="Ask a RAG question (POST)",
    description="Performs hybrid retrieval (BM25 + text-embedding-004) over indexed papers and generates a strictly-grounded answer with citations using Gemini 2.5 Flash.",
)
def query_post_endpoint(request: QueryRequest) -> QueryResponse:
    try:
        result = ask_question(
            question=request.question,
            alpha=request.alpha,
            top_k=request.top_k,
        )
        return QueryResponse(**result)
    except Exception as e:
        logger.error("Error evaluating RAG question: %s", e, exc_info=True)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Failed to generate RAG response: {str(e)}",
        )


@router.get(
    "/ask",
    response_model=Union[QueryResponse, Dict[str, Any]],
    summary="Ask a RAG question via browser / GET",
    description="Supports querying via browser or GET request using query parameters ?question=...&alpha=0.5&top_k=5. If no question is passed, returns usage guidelines.",
)
def query_get_endpoint(
    question: Optional[str] = Query(None, description="The research question to ask"),
    alpha: float = Query(0.5, ge=0.0, le=1.0, description="Hybrid balance: 0.0=sparse, 1.0=dense, 0.5=hybrid"),
    top_k: int = Query(5, ge=1, le=20, description="Number of context chunks to retrieve"),
):
    if not question:
        return {
            "status": "ready",
            "message": "Endpoint is active. Provide a 'question' query parameter to ask a question via GET, or send a POST request with JSON body.",
            "example_browser_url": "/ask?question=How+can+lung+cancer+be+detected+with+ML&alpha=0.5&top_k=3",
            "interactive_docs": "/docs",
        }

    try:
        result = ask_question(question=question, alpha=alpha, top_k=top_k)
        return QueryResponse(**result)
    except Exception as e:
        logger.error("Error evaluating RAG question (GET): %s", e, exc_info=True)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Failed to generate RAG response: {str(e)}",
        )


# Alias /query for convenience
@router.post("/query", response_model=QueryResponse, include_in_schema=False)
def query_alias_post(request: QueryRequest) -> QueryResponse:
    return query_post_endpoint(request)


@router.get("/query", response_model=Union[QueryResponse, Dict[str, Any]], include_in_schema=False)
def query_alias_get(
    question: Optional[str] = Query(None),
    alpha: float = Query(0.5, ge=0.0, le=1.0),
    top_k: int = Query(5, ge=1, le=20),
):
    return query_get_endpoint(question=question, alpha=alpha, top_k=top_k)


