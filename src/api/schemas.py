from typing import List, Optional, Union
from pydantic import BaseModel, Field


class QueryRequest(BaseModel):
    """
    Request payload for asking questions over indexed research documents.
    """
    question: str = Field(
        ...,
        description="The question or query to evaluate against the document corpus.",
        examples=["How can lung cancer be detected with ML?"],
        min_length=1,
    )
    alpha: Optional[float] = Field(
        default=0.5,
        ge=0.0,
        le=1.0,
        description="Hybrid weighting: 0.0 = pure BM25 sparse keyword search, 1.0 = pure dense semantic search, 0.5 = balanced hybrid.",
        examples=[0.5],
    )
    top_k: Optional[int] = Field(
        default=5,
        ge=1,
        le=20,
        description="Number of top relevant chunks to retrieve for LLM grounding.",
        examples=[5],
    )


class SourceCitation(BaseModel):
    """
    Information about a retrieved source chunk used in generating the answer.
    """
    document: str = Field(..., description="Path or filename of the cited document.")
    page: Optional[Union[int, str]] = Field(None, description="Page number of the cited content.")
    snippet: Optional[str] = Field(None, description="Preview snippet of the chunk.")
    score: Optional[float] = Field(None, description="Retrieval similarity / relevance score.")


class QueryResponse(BaseModel):
    """
    Response payload containing the grounded answer and citations.
    """
    question: str = Field(..., description="The original user question.")
    answer: str = Field(..., description="Grounded, plain-text response generated by the model.")
    alpha: float = Field(..., description="The alpha weight applied for retrieval.")
    top_k: int = Field(..., description="The number of documents retrieved.")
    sources: List[SourceCitation] = Field(default_factory=list, description="List of source passages retrieved and cited.")


class IngestRequest(BaseModel):
    """
    Request payload to trigger document ingestion and hybrid indexing.
    """
    docs_dir: Optional[str] = Field(
        default=None,
        description="Custom directory containing PDF documents (defaults to './ai-docs').",
    )
    reindex: bool = Field(
        default=False,
        description="Whether to force re-indexing even if the namespace already contains vectors.",
    )


class IngestResponse(BaseModel):
    """
    Response payload reporting ingestion pipeline results.
    """
    status: str = Field(..., description="Ingestion execution status ('success' or 'skipped').")
    message: str = Field(..., description="Detailed status message.")
    namespace: str = Field(..., description="Pinecone index namespace.")
    total_documents: Optional[int] = Field(None, description="Total PDF documents processed.")
    chunks_ingested: int = Field(..., description="Number of text chunks upserted.")
    current_vector_count: Optional[int] = Field(None, description="Total vectors in namespace after run.")


class HealthResponse(BaseModel):
    """
    System status and Pinecone index metadata.
    """
    status: str = Field(..., description="Health status of the API service.")
    index_name: str = Field(..., description="Name of the Pinecone index.")
    metric: str = Field(..., description="Distance metric used by the index (e.g., 'dotproduct').")
    dimension: int = Field(..., description="Vector dimension of embeddings (e.g., 768).")
    namespace: str = Field(..., description="Configured namespace for research documents.")
    namespace_vectors: int = Field(..., description="Vector count in target namespace.")
    total_index_vectors: int = Field(..., description="Total vector count across all namespaces.")
